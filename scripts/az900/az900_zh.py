#!/usr/bin/env python3
"""簡體 → 台灣正體，並套用 Azure 台灣官方術語。

OpenCC 的 s2twp 已經處理掉大部分用語差異（数据→資料、网络→網路、软件→軟體），
但它是通用詞庫，Azure 專有名詞會翻錯，最嚴重的是「实例 → 例項」（正確是
「執行個體」）。所以轉換後再套一層術語表。

順序很重要：長詞在前，否則「多重身份驗證」會先被「身份驗證」吃掉。TERMS
是有序 list 而不是 dict，就是為了鎖住這個順序。
"""
import re
from opencc import OpenCC

_cc = OpenCC('s2twp')

# (pattern, replacement)；pattern 是 regex，套用在 s2twp 轉完的正體字串上。
TERMS = [
    # ── OpenCC 沒轉到或轉錯的 ──
    (r'擴充套件', '擴展'),              # 扩展 → 擴充套件（詞庫把「扩展包」的用法套上來了）
    (r'許可權', '權限'),                # 权限 → 許可權
    (r'幹預', '干預'),
    (r'影象', '影像'),
    (r'公共雲', '公有雲'),
    (r'資料倉庫', '資料倉儲'),
    (r'云', '雲'),                      # 「云」本身是正體字，s2twp 不會動它
    (r'例項', '執行個體'),               # 实例 → 例項 是簡轉繁的通病
    (r'賬戶', '帳戶'),
    (r'雲端計算', '雲端運算'),
    # ── Azure 台灣官方術語（長詞優先）──
    (r'基於角色的訪問控制', '角色型存取控制'),
    (r'多重身份驗證', '多重要素驗證'),
    (r'雙因素身份驗證', '雙因素驗證'),
    (r'服務(級別|水平)協議', '服務等級協定'),
    (r'(地理|異地)備援儲存|地理冗餘儲存', '異地備援儲存體'),
    (r'本地冗餘儲存|本機冗餘儲存', '本機備援儲存體'),
    (r'(區域|割槽)冗餘儲存', '區域備援儲存體'),
    (r'儲存帳戶', '儲存體帳戶'),
    (r'網路安全組', '網路安全性群組'),
    (r'虛擬機器規模集|規模集', '虛擬機器擴展集'),
    (r'可用性集(?!群)', '可用性設定組'),
    (r'定價計算器', '定價計算機'),
    (r'總擁有成本計算器', '總擁有成本計算機'),
    (r'災難恢復|容災', '災害復原'),
    (r'故障轉移', '容錯移轉'),
    (r'角色分配', '角色指派'),
    (r'資源鎖(?!定)', '資源鎖定'),
    (r'管理組(?!織)', '管理群組'),
    (r'資源組(?!織)', '資源群組'),
    (r'支援計劃|支援計畫', '支援方案'),
    (r'按需付費|即用即付', '隨用隨付'),
    (r'預留執行個體', '保留執行個體'),
    (r'自動縮放|彈性伸縮|自動伸縮', '自動調整'),
    (r'知識挖掘', '知識探勘'),
    (r'正常執行時間', '正常運作時間'),
    (r'訂閱', '訂用帳戶'),
    (r'門戶', '入口網站'),
    (r'負載均衡', '負載平衡'),
    (r'身份驗證', '身分驗證'),
    (r'身份', '身分'),
    (r'訪問', '存取'),
    (r'冗餘', '備援'),
    (r'策略', '原則'),
    (r'監控', '監視'),
    (r'警報', '警示'),
    (r'遷移', '移轉'),
    (r'日誌', '記錄檔'),
    (r'子網(?!路)', '子網路'),
    (r'補丁', '修補程式'),
    (r'合規(?!性)', '合規性'),
    # ── 語氣統一（既有 AZ-104 題庫用「你」）──
    (r'您', '你'),
]

_COMPILED = [(re.compile(p), r) for p, r in TERMS]


def to_tw(text):
    """簡體（或已是正體）→ 台灣正體 + Azure 術語。"""
    if not text:
        return text
    out = _cc.convert(text)
    for pat, rep in _COMPILED:
        out = pat.sub(rep, out)
    return out


if __name__ == '__main__':
    import sys
    print(to_tw(sys.stdin.read()))
